#!/usr/bin/env python3
"""
graph_fixer.py — REPAIR the knowledge graph: link the orphan notes

WHAT: The Obsidian vault (149 notes) is generated by obsidian_vault_builder.py,
which wires wiki-links via SERVICES/BOTS/AGENTS maps. But notes NOT covered by
those maps (web-ui, github, SOP_WIKI, GAP_ANALYSIS) are written WITHOUT any
[[wiki-links]] — they float as orphans in the graph, invisible to navigation,
the graph view, and any agent that traverses links.

This agent:
  1. SCANS the vault for orphan notes (0 outgoing wiki-links)
  2. INFERS sensible links from the note's content (what it mentions)
  3. APPENDS a "## Related" section with [[links]] to related notes
  4. REGENERATES graph.html / graph_widget.html so the graph reflects it
  5. REPORTS what it fixed + what's still orphaned

WHY this matters: the vault is the system's memory graph. Orphan notes are
invisible to graph traversal, Obsidian's graph view, and the agents that read
links to decide what's related. An unlinked wiki is a broken wiki.

Usage:
    python graph_fixer.py --check      # list orphans (dry run)
    python graph_fixer.py --fix        # link orphans + rebuild graph
    python graph_fixer.py --status     # vault health
"""

import json
import logging
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
VAULT = Path.home() / "ObsidianVault" / "EsprieAether"
LOG_FILE = BASE_DIR / "data" / "graph_fixer_log.json"

logger = logging.getLogger("graph_fixer")
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    handlers=[
        logging.FileHandler(BASE_DIR / "data" / "logs" / "graph_fixer.log", encoding="utf-8"),
        logging.StreamHandler(sys.stdout),
    ],
)

# ── manual link map for known orphans (content-informed) ──
# note stem -> list of related note stems that SHOULD be linked
MANUAL_LINKS = {
    "web-ui": ["web", "control-center", "mobile", "router", "homedock"],
    "github": ["cloud", "VPS", "Sunna", "all-integrations"],
    "SOP_WIKI": ["devis", "Sunna", "prices", "factures", "kanban", "all-services"],
    "GAP_ANALYSIS": ["all-services", "control-center", "SOP_WIKI", "all-integrations",
                     "vector_memory", "colibri", "agent_mesh"],
    "task_executor": ["agent_mesh", "digest", "orchestrator"],
    "self_improve": ["agent_mesh", "memory", "digest"],
    "cherry_bridge": ["router", "colibri", "agent_mesh"],
    "jarvis_dev": ["agent_mesh", "colibri", "skill_harvester"],
}


def note_stems():
    """All note names (without .md) in the vault."""
    if not VAULT.exists():
        return set()
    return {p.stem for p in VAULT.rglob("*.md") if p.name != "graph.html"}


def outgoing_links(md_path):
    """Wiki-links present in a note."""
    try:
        text = md_path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return []
    # [[link]] or [[link|alias]]
    return re.findall(r"\[\[([^\]|#]+)", text)


def find_orphans():
    """Notes with zero outgoing wiki-links."""
    orphans = []
    if not VAULT.exists():
        return orphans
    for md in VAULT.rglob("*.md"):
        if md.name == "graph.html":
            continue
        links = outgoing_links(md)
        if not links:
            orphans.append(md)
    return orphans


def infer_links(md_path, all_stems):
    """
    Infer which existing notes this note should link to.
    Strategy: (1) manual map, (2) content keyword match against note stems.
    """
    stem = md_path.stem
    candidates = list(MANUAL_LINKS.get(stem, []))

    # content-based: if note text mentions another note's stem, link it
    try:
        text = md_path.read_text(encoding="utf-8", errors="ignore").lower()
    except Exception:
        text = ""
    for s in all_stems:
        if s == stem:
            continue
        # match whole-word-ish (avoid substring noise)
        if re.search(rf"\b{re.escape(s.lower())}\b", text) and s not in candidates:
            candidates.append(s)

    # cap: don't over-link
    return [c for c in candidates if c in all_stems][:8]


def link_note(md_path, links):
    """Append a Related section with wiki-links. Returns True if written."""
    if not links:
        return False
    try:
        text = md_path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return False

    # don't double-add
    if "## 🔗 Related" in text or "## Related" in text:
        return False

    link_lines = "\n".join(f"- [[{l}]]" for l in links)
    section = f"\n\n---\n\n## 🔗 Related (auto-linked by graph_fixer)\n\n{link_lines}\n"

    # preserve frontmatter, append at end
    md_path.write_text(text.rstrip() + "\n" + section, encoding="utf-8")
    return True


def rebuild_graph():
    """Regenerate graph.html + graph_widget.html via the vault builder."""
    builder = BASE_DIR / "src" / "obsidian_vault_builder.py"
    if not builder.exists():
        return {"ok": False, "reason": "builder not found"}
    try:
        r = subprocess.run(
            [sys.executable, str(builder)],
            capture_output=True, text=True, timeout=120,
            cwd=str(BASE_DIR),
        )
        return {"ok": r.returncode == 0, "stderr": r.stderr[-200:] if r.stderr else ""}
    except Exception as e:
        return {"ok": False, "error": str(e)[:150]}


def log_action(entry):
    log = []
    if LOG_FILE.exists():
        try:
            log = json.loads(LOG_FILE.read_text(encoding="utf-8"))
        except Exception:
            log = []
    log.append(entry)
    log = log[-50:]
    LOG_FILE.parent.mkdir(exist_ok=True)
    LOG_FILE.write_text(json.dumps(log, ensure_ascii=False, indent=1), encoding="utf-8")


def fix():
    """Link all orphans + rebuild graph. Returns summary."""
    all_stems = note_stems()
    orphans = find_orphans()
    fixed = []
    still_orphan = []

    for md in orphans:
        links = infer_links(md, all_stems)
        if link_note(md, links):
            fixed.append({"note": md.stem, "links": links})
            logger.info(f"🔗 linked {md.stem} → {links}")
        else:
            still_orphan.append(md.stem)

    graph = rebuild_graph()

    result = {
        "orphans_found": len(orphans),
        "fixed": len(fixed),
        "still_orphan": still_orphan,
        "graph_rebuilt": graph.get("ok", False),
        "total_notes": len(all_stems),
    }
    log_action({"ts": datetime.now(timezone.utc).isoformat(), **result})
    return result


def status():
    orphans = find_orphans()
    all_stems = note_stems()
    lines = ["🕸️ *Graph Fixer*", ""]
    lines.append(f"الملاحظات: `{len(all_stems)}`")
    lines.append(f"معلّقة (orphans): `{len(orphans)}`")
    if orphans:
        lines += ["", "🔴 مقطوعة من الـ graph:"]
        for md in orphans[:10]:
            lines.append(f"• `{md.stem}`")
    else:
        lines += ["", "✅ كل الملاحظات مربوطة"]
    return "\n".join(lines)


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--fix", action="store_true")
    ap.add_argument("--status", action="store_true")
    args = ap.parse_args()

    if args.check:
        orphans = find_orphans()
        print(json.dumps({
            "orphans": [m.stem for m in orphans],
            "total_notes": len(note_stems()),
        }, ensure_ascii=False, indent=2))
    elif args.status:
        print(status())
    else:  # default: fix
        r = fix()
        print(json.dumps(r, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
