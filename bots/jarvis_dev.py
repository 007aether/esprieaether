#!/usr/bin/env python3
"""
jarvis_dev.py — JARVIS as an AGENT DEVELOPER: write NEW mesh agents from ideas

WHAT: Until now, mesh agents THINK and task_executor RUNS their tasks — but
nobody WRITES new agents. JARVIS-dev is the missing piece: it reads ideas
from the system (skill_candidates, veille, executor feedback), asks the
router (colibri 30B / ollama / cloud) to write a NEW agent module, validates
it (syntax + import), and stages it in src/ for review before it joins the mesh.

THE LOOP:
    skill_candidates / veille → [JARVIS-dev] → writes agent code
        → syntax check + import test → stage in src/_staged/ → (review) → join mesh

WHY staged (not auto-join): a generated agent is code that will run in the
mesh loop. We stage it, test it, and only wire it into agent_mesh AGENTS +
autonomous_loop after validation. Safety first — no unvetted code runs 24/7.

Usage:
    python jarvis_dev.py --once          # write 1 new agent from top idea
    python jarvis_dev.py --idea "X"      # write agent for a specific idea
    python jarvis_dev.py --status        # what's staged / written / joined
"""

import ast
import json
import logging
import os
import subprocess
import sys
import time
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
STAGE_DIR = BASE_DIR / "src" / "_staged"          # generated agents land here
LOG_FILE = BASE_DIR / "data" / "jarvis_dev_log.json"
IDEAS_FILE = BASE_DIR / "data" / "skill_candidates.json"

ROUTER_URL = os.getenv("AETHER_ROUTER_URL", "http://127.0.0.1:11435")
STAGED_AGENTS = []  # this run

logger = logging.getLogger("jarvis_dev")
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    handlers=[
        logging.FileHandler(BASE_DIR / "data" / "logs" / "jarvis_dev.log", encoding="utf-8"),
        logging.StreamHandler(sys.stdout),
    ],
)

# ── agent template — the contract every generated agent must satisfy ──
AGENT_TEMPLATE = '''#!/usr/bin/env python3
"""
{module_name}.py — {title}

{description}

Auto-generated by jarvis_dev from idea: {idea}
Created: {ts}
"""
import json
import logging
from datetime import datetime, timezone
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
logger = logging.getLogger("{module_name}")

# ── CONFIG — every agent declares its own schedule + tags ──
INTERVAL_MIN = {interval}
TAGS = {tags}

def gather() -> dict:
    """Collect this agent's data. MUST return a dict."""
    return {{"status": "ok", "ts": datetime.now(timezone.utc).isoformat()}}

def main() -> int:
    """Entry point. Return 0 on success."""
    data = gather()
    logger.info(f"[{module_name}] {{data}}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
'''


def ask_router(prompt, system="You are JARVIS, an expert Python developer. Write clean, working, well-commented code. Respond with ONLY a complete Python module."):
    """Ask the router (colibri 30B / ollama / cloud) to generate code."""
    messages = [
        {"role": "system", "content": system},
        {"role": "user", "content": prompt},
    ]
    try:
        data = json.dumps({"model": "aether-auto", "messages": messages, "max_tokens": 2000}).encode()
        req = urllib.request.Request(f"{ROUTER_URL}/v1/chat/completions", data=data, method="POST")
        req.add_header("Content-Type", "application/json")
        with urllib.request.urlopen(req, timeout=90) as r:
            result = json.loads(r.read().decode())
            return result["choices"][0]["message"]["content"]
    except Exception as e:
        logger.error(f"router error: {e}")
        return None


def load_ideas():
    """Load candidate ideas from skill_candidates."""
    if not IDEAS_FILE.exists():
        return []
    try:
        data = json.loads(IDEAS_FILE.read_text(encoding="utf-8"))
        items = data if isinstance(data, list) else data.get("candidates", [])
        return [i for i in items if isinstance(i, dict)][:20]
    except Exception:
        return []


def pick_idea(ideas, exclude=None):
    """Pick the best un-worked idea (highest stars, not already written)."""
    exclude = exclude or set()
    best = None
    for idea in ideas:
        repo = str(idea.get("repo", idea.get("name", "")))
        stars = idea.get("stars", 0)
        # skip if already staged
        module = to_module_name(repo)
        if module in exclude or (STAGE_DIR / f"{module}.py").exists():
            continue
        if best is None or stars > best.get("stars", 0):
            best = idea
    return best


def to_module_name(repo):
    """CherryHQ/cherry-studio → cherry_studio_agent"""
    name = repo.split("/")[-1] if "/" in repo else repo
    name = name.replace("-", "_").replace(".", "_").lower()
    if not name.endswith("agent"):
        name += "_agent"
    return name[:40]


def validate_code(code, module_name):
    """Syntax + import + safety checks. Returns (ok, errors)."""
    errors = []

    # 1. syntax
    try:
        tree = ast.parse(code)
    except SyntaxError as e:
        return False, [f"syntax error line {e.lineno}: {e.msg}"]

    # 2. must have a main() or gather()
    has_main = any(
        isinstance(n, ast.FunctionDef) and n.name in ("main", "gather", "run")
        for n in ast.walk(tree)
    )
    if not has_main:
        errors.append("missing main()/gather()/run() entry point")

    # 3. safety: no destructive ops in generated code
    dangerous = ["os.remove", "shutil.rmtree", "subprocess.run(['rm'", "os.system('rm",
                 "format(", "del ", "__import__('os').remove"]
    for d in dangerous:
        if d in code:
            errors.append(f"dangerous construct: {d}")

    # 4. no secrets
    for secret_kw in ["api_key =", "token =", "password =", "secret ="]:
        if secret_kw in code.lower():
            errors.append(f"possible hardcoded secret: {secret_kw}")

    # 5. module docstring present
    if not (tree.body and isinstance(tree.body[0], ast.Expr) and isinstance(tree.body[0].value, ast.Constant)):
        errors.append("missing module docstring")

    return len(errors) == 0, errors


def write_agent(idea, code):
    """Write validated agent to staging."""
    repo = str(idea.get("repo", idea.get("name", "unknown")))
    module = to_module_name(repo)
    STAGE_DIR.mkdir(exist_ok=True)
    path = STAGE_DIR / f"{module}.py"

    # ensure header + template contract even if router output is partial
    if "def main(" not in code and "def gather(" not in code:
        code = AGENT_TEMPLATE.format(
            module_name=module,
            title=str(idea.get("description", idea.get("name", "agent")))[:80],
            description=f"Agent for: {repo} ({idea.get('stars', '?')}★)\n{idea.get('description', '')}",
            idea=repo,
            ts=datetime.now(timezone.utc).isoformat(),
            interval=60,
            tags='["generated", "jarvis_dev"]',
        )

    path.write_text(code, encoding="utf-8")
    return module, path


def log_action(entry):
    log = []
    if LOG_FILE.exists():
        try:
            log = json.loads(LOG_FILE.read_text(encoding="utf-8"))
        except Exception:
            log = []
    log.append(entry)
    log = log[-100:]
    LOG_FILE.parent.mkdir(exist_ok=True)
    LOG_FILE.write_text(json.dumps(log, ensure_ascii=False, indent=1), encoding="utf-8")


def develop_once(idea_text=None):
    """Write ONE new agent. Returns summary."""
    ideas = load_ideas()

    if idea_text:
        idea = {"repo": idea_text, "stars": 0, "description": f"custom: {idea_text}"}
    else:
        idea = pick_idea(ideas)
        if not idea:
            return {"written": 0, "reason": "no un-worked ideas left"}

    repo = str(idea.get("repo", idea.get("name", "?")))
    logger.info(f"🧠 developing agent for: {repo} ({idea.get('stars','?')}★)")

    prompt = (
        f"Write a complete Python module for an autonomous agent in the EsprieAether system.\n"
        f"IDEA: {repo} — {idea.get('description','')}\n\n"
        f"REQUIREMENTS:\n"
        f"- Module docstring explaining what it does (in Arabic + English)\n"
        f"- A `def gather() -> dict` that collects data (or `def main() -> int`)\n"
        f"- INTERVAL_MIN, TAGS module constants\n"
        f"- Clean, stdlib-only (no pip installs), well-commented\n"
        f"- NO secrets, NO destructive ops, NO network calls without a URL constant\n"
        f"- Working, syntactically valid Python 3\n\n"
        f"Write ONLY the Python code, no markdown fences."
    )

    code = ask_router(prompt)
    if not code:
        result = {"written": 0, "error": "router failed", "idea": repo}
        log_action({"ts": datetime.now(timezone.utc).isoformat(), **result})
        return result

    # strip markdown fences if present
    code = code.strip()
    if code.startswith("```"):
        code = code.split("\n", 1)[1] if "\n" in code else code
        code = code.rsplit("```", 1)[0]

    module, path = write_agent(idea, code)

    # validate
    ok, errors = validate_code(path.read_text(encoding="utf-8"), module)
    result = {
        "written": 1 if ok else 0,
        "idea": repo,
        "module": module,
        "path": str(path),
        "valid": ok,
        "errors": errors,
    }
    if not ok:
        # quarantine invalid output
        path.rename(path.with_suffix(".py.invalid"))
        logger.warning(f"❌ {module} invalid: {errors}")
    else:
        STAGED_AGENTS.append(module)
        logger.info(f"✅ {module} staged at {path}")

    log_action({"ts": datetime.now(timezone.utc).isoformat(), **result})
    return result


def status():
    """JARVIS-dev status for Telegram."""
    staged = list(STAGE_DIR.glob("*.py")) if STAGE_DIR.exists() else []
    invalid = list(STAGE_DIR.glob("*.py.invalid")) if STAGE_DIR.exists() else []
    log = []
    if LOG_FILE.exists():
        try:
            log = json.loads(LOG_FILE.read_text(encoding="utf-8"))
        except Exception:
            log = []

    lines = ["🧠 *JARVIS Developer*", ""]
    lines.append(f"أفكار متاحة: `{len(load_ideas())}`")
    lines.append(f"مكتوب (staged): `{len(staged)}` · مرفوض: `{len(invalid)}`")
    lines.append(f"سجل: `{len(log)}` عملية")
    if staged:
        lines += ["", "📝 جاهز للمراجعة:"]
        for p in staged[:5]:
            lines.append(f"• `{p.stem}`")
    if invalid:
        lines += ["", "❌ مرفوض (باغي إصلاح):"]
        for p in invalid[:3]:
            lines.append(f"• `{p.stem}`")
    return "\n".join(lines)


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--once", action="store_true")
    ap.add_argument("--daemon", action="store_true")
    ap.add_argument("--idea", type=str, help="develop agent for a specific idea")
    ap.add_argument("--status", action="store_true")
    args = ap.parse_args()

    if args.status:
        print(status())
        return

    if args.daemon:
        logger.info("═" * 50)
        logger.info("JARVIS Developer — writing agents from ideas")
        logger.info("═" * 50)
        while True:
            try:
                r = develop_once()
                if r.get("written"):
                    logger.info(f"✅ wrote {r.get('module')} for {r.get('idea')}")
            except Exception as e:
                logger.error(f"cycle error: {e}")
            time.sleep(30 * 60)  # 30 min

    r = develop_once(idea_text=args.idea)
    print(json.dumps(r, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
