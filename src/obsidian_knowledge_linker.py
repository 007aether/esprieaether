class ObsidianKnowledgeLinker:
    """
    Links EsprieAether knowledge base with Obsidian vault.
    
    Features:
      • Sync knowledge to Obsidian notes
      • Link knowledge files to Obsidian notes
      • Track development statistics
      • Link files between systems
      • Improve frontend experience
    """

    def __init__(self, esprie_dir: str, obsidian_dir: str):
        self.esprie_dir = Path(esprie_dir)
        self.obsidian_dir = Path(obsidian_dir)
        self.knowledge_dir = self.esprie_dir / "data" / "knowledge_base"
        self.knowledge_index = self.knowledge_dir / "knowledge_index.json"

        # Obsidian vault structure
        self.vault_categories = {
            "Agents": "Agents",
            "Brains": "Brains",
            "Docs": "Docs",
            "Infra": "Infra",
            "Integrations": "Integrations",
            "Meta": "Meta",
            "Services": "Services",
            "Sunna": "Sunna",
        }

    def link_knowledge_to_obsidian(self) -> dict:
        """Link knowledge base items to Obsidian notes."""
        result = {
            "status": "linked",
            "linked_count": 0,
            "failed": [],
            "timestamp": datetime.now(_tz.utc).isoformat(),
        }

        if not self.knowledge_index.exists():
            result["status"] = "no_knowledge_index"
            return result

        with open(self.knowledge_index, encoding="utf-8") as f:
            knowledge_data = json.load(f)

        linked = 0
        missing = []

        for item in knowledge_data.get("items", []):
            # Use "text" field as title if no title exists
            title = item.get("title", item.get("text", ""))
            content = item.get("text", item.get("content", ""))
            tags = item.get("tags", [])

            # Find or create Obsidian note
            obsidian_note = self._find_or_create_note(title, tags)

            if obsidian_note:
                # Link knowledge to note
                self._link_knowledge_to_note(obsidian_note, title, content, tags)
                linked += 1
            else:
                missing.append({"title": title, "error": "Could not create note"})

        result["linked_count"] = linked
        result["missing"] = missing
        return result

    def _find_or_create_note(self, title: str, tags: list) -> str:
        """Find or create an Obsidian note for knowledge item."""
        # Check if note exists by category
        for cat, folder in self.vault_categories.items():
            cat_dir = self.obsidian_dir / folder
            if cat_dir.exists():
                for file in cat_dir.glob("*.md"):
                    if title.lower() in file.stem.lower():
                        return str(file)

        # Create new note
        note_path = self._create_obsidian_note(title, tags)
        return str(note_path)

    def _create_obsidian_note(self, title: str, tags: list) -> Path:
        """Create a new Obsidian note."""
        # Determine category based on tags
        cat = "Meta"  # default
        for tag in tags:
            if tag in self.vault_categories:
                cat = self.vault_categories[tag]
                break

        cat_dir = self.obsidian_dir / cat
        cat_dir.mkdir(parents=True, exist_ok=True)

        # Generate unique filename
        safe_title = "".join(c for c in title if c.isalnum() or c in " -_")[:50]
        file_path = cat_dir / f"{safe_title}.md"

        # Create note content
        content = f"""---
title: {title}
tags: {tags}
created: {datetime.now(timezone.utc()).isoformat()}
updated: {datetime.now(timezone.utc()).isoformat()}
source: EsprieAether Knowledge Base
status: {{"active"}}
---

# {title}

{{content[:2000]}}

---
tags: [{", ".join(tags)}]
aliases: []
---

*Generated by EsprieAether Knowledge Linker*
"""
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(content)

        return file_path

    def _link_knowledge_to_note(self, note_path: str, title: str, content: str, tags: list):
        """Link knowledge to existing note."""
        try:
            with open(note_path, encoding="utf-8") as f:
                existing = f.read()

            # Add link at top
            link_header = f"\n## Knowledge Link\n- Source: {{title}}\n- Created: {datetime.now(timezone.utc()).isoformat()}\n---\n\n"
            if "Knowledge Link" not in existing:
                with open(note_path, "w", encoding="utf-8") as f:
                    f.write(link_header + "\n" + existing)
        except Exception:
            pass

